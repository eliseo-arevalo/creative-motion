#!/usr/bin/env bash
# Rhubarb wrapper: wav (+ optional transcript) -> mouth cues.
#   lipsync.sh in.wav out.json            # Rhubarb JSON
#   lipsync.sh in.wav out.ts [name]       # TypeScript module exporting MouthCue[]
#   TEXT=transcript.txt lipsync.sh ...    # optional dialog file (helps the English recognizer most)
# Uses the language-independent "phonetic" recognizer (works for Spanish).
set -euo pipefail
IN="${1:?usage: lipsync.sh in.wav out.(json|ts) [exportName]}"
OUT="${2:?usage: lipsync.sh in.wav out.(json|ts) [exportName]}"
NAME="${3:-$(basename "${OUT%.*}" | tr -c 'A-Za-z0-9\n' '_')}"
RHUBARB="${RHUBARB:-$(command -v rhubarb || echo "$HOME/tools/Rhubarb-Lip-Sync-1.14.0-Linux/rhubarb")}"
TMP="$(mktemp --suffix=.json)"
ARGS=(-q -r phonetic -f json --extendedShapes GHX -o "$TMP")
[[ -n "${TEXT:-}" ]] && ARGS+=(-d "$TEXT")
"$RHUBARB" "${ARGS[@]}" "$IN"
if [[ "$OUT" == *.ts ]]; then
  node -e '
    const j = JSON.parse(require("fs").readFileSync(process.argv[1], "utf8"));
    const cues = j.mouthCues.map((c) => `  { start: ${c.start}, end: ${c.end}, value: "${c.value}" },`).join("\n");
    process.stdout.write(`// Generated by character-kit/scripts/lipsync.sh from ${require("path").basename(process.argv[3])} (Rhubarb, phonetic).\nimport type { MouthCue } from "@eliseo-arevalo/character-kit";\n\nexport const ${process.argv[2]}: MouthCue[] = [\n${cues}\n];\n`);
  ' "$TMP" "$NAME" "$IN" > "$OUT"
else
  mv "$TMP" "$OUT"
fi
rm -f "$TMP"
echo "wrote $OUT"
